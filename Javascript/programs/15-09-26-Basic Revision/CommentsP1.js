// JavaScript Comments
// ============================================================

// Single Line Comment
// A single-line comment is used to write explanations
// or notes in the code.
// JavaScript ignores comments during execution.
console.log("Hi");
// This is a single line comment
console.log("Hello");

// Multi-Line Comment
// ============================================================

// A multi-line comment is used when the comment
// contains multiple lines of information.
/*
This is a
Multiline comment
Hi
Hello
*/
console.log("Hello");
