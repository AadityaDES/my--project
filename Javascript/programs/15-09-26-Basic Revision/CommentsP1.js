// Features of JavaScript
// ============================================================
// 1. Lightweight
// JavaScript is a lightweight programming language
// designed to perform tasks efficiently.

// 2. Dynamically Typed
// We do not need to specify the data type of a variable.
// The data type is determined at runtime.

let value = 100;
value = "Hello";

// 3. Interpreted / Just-In-Time Compiled
// JavaScript code is executed by a JavaScript engine.
// Modern JavaScript engines parse and compile code
// at runtime for better performance.

// 4. Object-Based / Prototype-Based
// JavaScript uses objects and a prototype-based object model
// to organize and reuse data and behavior.

// 5. Platform Independent
// JavaScript can run on different operating systems
// and platforms when a compatible JavaScript engine is available.

// 6. Case Sensitive
// JavaScript is case sensitive.
// Variable names with different letter cases are different.

let name = "John";
let Name = "David";

// name and Name are different variables.

// 7. Dynamically Executed
// The same JavaScript code can execute in different
// environments such as browsers, Node.js, and automation tools.

// 8. Supports Object-Oriented Programming
// JavaScript supports concepts such as:
// Objects, Classes, Encapsulation, Inheritance, and Polymorphism.